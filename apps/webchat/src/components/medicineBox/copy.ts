export const medicineBoxCopy = { zh, en } satisfies Record<Language, typeof zh>;
export type MedicineCopy = typeof zh;

export const fill = (template: string, values: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/gu, (match, key: string) => key in values ? String(values[key]) : match);

export const quantityText = (copy: MedicineCopy, quantity: number, unit: MedicineUnit) => `${quantity}${copy.unitSeparator}${copy.units[unit]}`;

// A YYYY-MM-DD date, read as a local calendar day.
export function formatDate(copy: MedicineCopy, date: string) {
  const [year, month, day] = date.slice(0, 10).split("-").map(Number);
  if (!year || !month || !day) return date;
  return new Intl.DateTimeFormat(copy.locale, { year: "numeric", month: copy.locale === "zh-CN" ? "long" : "short", day: "numeric" }).format(new Date(year, month - 1, day));
}

export function statusText(copy: MedicineCopy, item: Pick<MedicineItem, "expires_on" | "no_expiry">, status: MedicineStatus = medicineStatus(item)) {
  switch (status) {
    case "expired": return copy.expired;
    case "expiring": {
      const days = medicineDaysLeft(item.expires_on) ?? 0;
      return days === 0 ? copy.expiresToday : fill(copy.expiresIn, { days });
    }
    case "ok": return copy.notExpiring;
    case "none": return copy.withoutExpiry;
    case "unknown": return copy.noExpiry;
  }
}

export function expiryText(copy: MedicineCopy, item: Pick<MedicineItem, "expires_on" | "no_expiry">) {
  return item.no_expiry ? copy.withoutExpiry : item.expires_on ? formatDate(copy, item.expires_on) : copy.notSet;
}

export function medicineWriteProblem(error: unknown, copy: MedicineCopy, fallback: string) {
  return error && typeof error === "object" && "code" in error && error.code === "medicine_conflict" ? copy.conflict : fallback;
}
