import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'tools/ezmcd-adapter');
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
async function files(dir,prefix='') {
 const result={};
 for(const entry of (await fs.readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name,'en'))) {
  if(entry.name==='__pycache__'||entry.name.endsWith('.pyc'))continue;
  const name=prefix+entry.name;
  if(entry.isSymbolicLink())throw new Error('Adapter source may not contain symlinks');
  if(entry.isDirectory())Object.assign(result,await files(path.join(dir,entry.name),name+'/'));
  else result[name]=hash(await fs.readFile(path.join(dir,entry.name)));
 }
 return Object.fromEntries(Object.entries(result).sort(([a],[b])=>a<b?-1:a>b?1:0));
}
const lock=JSON.parse(await fs.readFile(path.join(source,'upstream.lock.json')));
const contract={schema_version:1,python:lock.python,adapter_revision:lock.adapter_revision,upstream_revision:lock.revision,patch_sha256:lock.patches.map(p=>p.sha256),adapter_source_sha256:hash(JSON.stringify(await files(path.join(source,'src')))),dependencies_sha256:hash(await fs.readFile(path.join(source,'requirements.txt')))};
const json=JSON.stringify(contract,null,2)+'\n';
const outputs={
 'tools/ezmcd-adapter/runtime-contract.json':json,
 'apps/desktop/src/shared/ezmcd-runtime-contract.json':json,
 'services/gateway/internal/mcdintegration/runtime_contract_generated.go':`// Code generated by scripts/sync-ezmcd-contract.mjs; DO NOT EDIT.\npackage mcdintegration\n\nconst runtimeContractJSON = \x60${JSON.stringify(contract)}\x60\n`,
};
for(const [name,contents] of Object.entries(outputs)) {
 const file=path.join(root,name);
 if(process.argv.includes('--check')){if(await fs.readFile(file,'utf8')!==contents)throw new Error('EzMcDonalds runtime contract is stale: '+name);}
 else await fs.writeFile(file,contents);
}
