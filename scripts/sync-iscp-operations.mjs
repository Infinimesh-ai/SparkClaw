#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const raw = readFileSync(`${root}services/gateway/internal/iscpworkbench/operations.json`, 'utf8');
const registry = JSON.parse(raw);
const names = new Set();
for (const row of registry) {
  if (names.has(row.name)) throw new Error(`duplicate operation ${row.name}`);
  names.add(row.name);
}
const generated = `// Code generated by scripts/sync-iscp-operations.mjs; DO NOT EDIT.\npackage iscpworkbench\n\nconst (\n${registry.map(row => `\t${row.constant} = ${JSON.stringify(row.name)}`).join('\n')}\n)\n`;
mkdirSync(`${root}apps/desktop/src/shared`, { recursive: true });
for (const [path, value] of [['services/gateway/internal/iscpworkbench/operations_generated.go', generated], ['apps/desktop/src/shared/iscp-operations.json', raw]]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(root + path, 'utf8') !== value) throw new Error(`stale operation projection: ${path}`);
  } else writeFileSync(root + path, value);
}
