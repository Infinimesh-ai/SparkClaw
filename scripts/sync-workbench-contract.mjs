import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const limits = JSON.parse(await fs.readFile(path.join(root, "configs/workbench-limits.json"), "utf8"));
for (const [name, value] of Object.entries(limits)) {
  if (!/^[a-z][A-Za-z]+$/u.test(name) || !Number.isSafeInteger(value) || value <= 0) throw new Error("Invalid workbench limit");
}
const outputs = new Map([
  ["services/gateway/internal/app/workbench_limits.go", `// Code generated by scripts/sync-workbench-contract.mjs; DO NOT EDIT.\npackage app\n\nconst (\n${Object.entries(limits).map(([key, value]) => `\tWorkbench${key[0].toUpperCase()}${key.slice(1)} = ${value}`).join("\n")}\n)\n`],
  ["apps/desktop/src/shared/workbench-limits.mjs", `// Generated by scripts/sync-workbench-contract.mjs; do not edit.\nexport const WORKBENCH_LIMITS = Object.freeze(${JSON.stringify(limits, null, 2)});\n`],
]);
for (const [relative, output] of outputs) {
  const target = path.join(root, relative);
  // Go formatting is kept stable without depending on a Go toolchain in Mac packaging.
  const source = relative.endsWith(".go") ? output.replace(/(\tWorkbench\w+) = /gu, (_, key) => `${key}${" ".repeat(27 - key.length)}= `) : output;
  if (process.argv.includes("--check")) {
    if (await fs.readFile(target, "utf8") !== source) throw new Error(`Stale workbench contract: ${relative}`);
  } else {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, source);
  }
}
